def build_architecture() -> str:
    arch = load_module('journal_arch', 'scripts/build_english_architecture_figure.py')
    replacements = {
        'BatchLoader': ('BatchLoader', ['4 windows', '257 tokens each']),
        'AdamW update': ('AdamW update', ['lr = 1.5e-3', 'weight decay = 0.1']),
        'Cosine schedule': ('Cosine schedule', ['3% warmup', 'minimum lr = 0']),
        'Checkpoint': ('Checkpoint', ['10,488,640 parameters', '40.03 MiB']),
        'Frozen checkpoint': ('Frozen checkpoint', ['seed 17 selected', 'no test tuning']),
        'Test once after freeze': ('Test once after freeze',
                                   ['428,405 scored targets', 'final test BPB = 1.571349']),
    }
    patched = []
    for name in sorted(n for n in dir(arch) if n.endswith('_BOXES')):
        boxes = getattr(arch, name)
        for index, (title, _) in enumerate(boxes):
            if title in replacements:
                boxes[index] = replacements[title]
                patched.append(title)
    missing = set(replacements) - set(patched)
    if missing:
        raise SystemExit(f'architecture patch missed: {sorted(missing)}')
    return arch.build(), arch.W, arch.H


def write_png(svg_path: Path, png_path: Path, width: int = 2560, height: int = 1440) -> None:
    import cairosvg
    cairosvg.svg2png(url=str(svg_path), write_to=str(png_path),
                     output_width=width, output_height=height)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--skip-png', action='store_true')
    args = parser.parse_args()

    data = json.loads(DATA.read_text(encoding='utf-8'))
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    manifest = []

    for spec in specs(data):
        svg_text = figures.render_figure(spec['id'], '', '', '', spec['charts'])
        svg_path = OUT_DIR / f"{spec['id']}.svg"
        svg_path.write_text(svg_text, encoding='utf-8')
        has_cjk = any('\u4e00' <= ch <= '\u9fff' for ch in svg_text)
        if not args.skip_png:
            write_png(svg_path, OUT_DIR / f"{spec['id']}.png")
        manifest.append({'id': spec['id'], 'png': f"{spec['id']}.png", 'cjk': has_cjk})
        print(f"{'CJK!' if has_cjk else ' ok '} {spec['id']}")

    svg_text, width, height = build_architecture()
    svg_path = OUT_DIR / 'v13_architecture.svg'
    svg_path.write_text(svg_text, encoding='utf-8')
    has_cjk = any('\u4e00' <= ch <= '\u9fff' for ch in svg_text)
    if not args.skip_png:
        write_png(svg_path, OUT_DIR / 'v13_architecture.png',
                  width=2560, height=round(2560 * height / width))
    manifest.append({'id': 'v13_architecture', 'png': 'v13_architecture.png', 'cjk': has_cjk})
    print(f"{'CJK!' if has_cjk else ' ok '} v13_architecture")

    (OUT_DIR / 'manifest.json').write_text(
        json.dumps(manifest, indent=1) + '\n', encoding='utf-8')
    bad = [m['id'] for m in manifest if m['cjk']]
    if bad:
        raise SystemExit(f'figures contain CJK text: {bad}')
    print(f'\n{len(manifest)} figures -> {OUT_DIR.relative_to(PROJECT)}')


if __name__ == '__main__':
    main()
