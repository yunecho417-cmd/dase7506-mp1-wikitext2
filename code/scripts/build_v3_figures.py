def load_module(name: str, relpath: str):
    spec = importlib.util.spec_from_file_location(name, ROOT / relpath)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


figures = load_module('journal_figures', 'scripts/build_english_journal_figures.py')

_original_fmt = figures.fmt


def fmt(value: float, chart: dict, precise: bool = False) -> str:
    """Renderer-compatible formatter with an explicit decimal budget."""
    tick_decimals = chart.get('decimals')
    if tick_decimals is None:
        return _original_fmt(value, chart, precise)
    decimals = chart.get('label_decimals', tick_decimals) if precise else tick_decimals
    return f'{value:.{decimals}f}'


figures.fmt = fmt


def chart(spec: dict) -> dict:
    return spec


